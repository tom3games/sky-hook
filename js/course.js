// SKY HOOK のコース。塔の外周を開いた2次元（x=周に沿った距離 m, y=高さ m）。
// 見た目（view.js）も当たり（physics.js）もこの一覧から作る。
// 区間ごとの「なぜワイヤーでないとダメか」は ideas/sky-hook.md の表。

export const TOWER_R = 30          // 遊ぶ面の半径（m）。塔の壁はこれより内側

export function makeCourse() {
  const C = { solids: [], anchors: [], hazards: [], gusts: [], flags: [], floods: [], sections: [], deco: [] }
  const A = (x, y, kind = 'ring', o = {}) => { C.anchors.push({ x, y, kind, ...o }); return C.anchors.length - 1 }
  const B = (x, y, w, h, o = {}) => { C.solids.push({ x, y, w, h, a: 0, mat: 'stone', ...o }); return C.solids.length - 1 }
  // 上面が y の岩棚（x0..x1）
  const ledge = (x0, x1, y, th = 1.4, o = {}) => B((x0 + x1) / 2, y - th / 2, x1 - x0, th, o)
  // 塔から張り出した柱（控え壁）。x0..x1, y0..y1
  const wall = (x0, x1, y0, y1, o = {}) => B((x0 + x1) / 2, (y0 + y1) / 2, x1 - x0, y1 - y0, o)
  const sec = (key, y0, y1, o = {}) => C.sections.push({ key, y0, y1, ...o })
  let cx = 0, cy = 0
  const R = (dx, dy, kind, o) => { cx += dx; cy += dy > 5 ? 5 + (dy - 5) * 0.4 : dy; return A(cx, cy, kind, o) }   // 道（5m より高い段は詰める: 届く高さは 6m まで）
  const D = (dx, dy, kind, o) => A(cx + dx, cy + dy, kind, o)                       // 寄り道・罠（今の位置から）
  const go = (x, y) => { cx = x; cy = y }
  // 旗: 旗を巻いた輪（掛けると記録）。左下に小さな足場（落ちたらここに戻る）
  const F = (dx, dy) => { const i = R(dx, dy, 'ring', { flag: true }); ledge(cx - 4.7, cx - 2.3, cy - 2.2, 0.6, { perch: true }); C.flags.push({ x: cx - 3.5, y: cy - 2.2, w: 2.4, a: i }); return i }

  // ============================================================ 1. 基部（こぐ・離す・選ぶ）
  // 主役: ふつうの輪。初めて見せる → 2つの道 → 張り出しを回り込む → 旗
  sec('base', -2, 42)
  ledge(-16, 0, 0, 6)                       // 出発の広場（右は切り立った崖）
  wall(-20, -16, -6, 34)                    // 左の控え壁
  A(4.5, 5)                                 // 0: 崖の先。掛けて右へ歩くと落ちて振れる
  A(11, 9.5)                                // 1: 右の道
  A(-2, 9.5)                                // 2: 左の道（広場の上へ振り戻す）
  A(17, 14)                                 // 3
  A(-8, 14)                                 // 4
  ledge(1, 11, 21, 1.0, { mat: 'wood' })    // 張り出した木の床（真上へは抜けられない）
  A(6, 16)                                  // 5: 罠。床の真下。掛けても上へ行けない
  A(12, 18)                                 // 6
  A(0, 18)                                  // 7
  A(16.5, 23)                               // 8: 床の右端を回る
  A(-2.5, 23)                               // 9: 左端を回る
  A(7, 27)                                  // 10: 床の上
  A(13.5, 31)                               // 11
  go(13.5, 31); F(6, 4)                     // 旗1
  wall(26, 30, 4, 30)                       // 右の控え壁

  // 以後は「ひとつ前の道の輪」からの相対位置で置く（1手で届く幅: 上へ 4〜6.5m・横へ 5〜9m）。
  // 地形・仕掛けも今の輪からの相対で置くので、手前を直しても後ろがずれない
  const P = () => [cx, cy]
  const rl = (dx0, dx1, top, th = 1.2, o) => ledge(cx + dx0, cx + dx1, cy + top, th, o)
  const rw = (dx0, dx1, dy0, dy1, o) => wall(cx + dx0, cx + dx1, cy + dy0, cy + dy1, o)
  const rB = (dx, dy, w, h, o) => B(cx + dx, cy + dy, w, h, o)
  const rG = (dx0, dx1, dy0, dy1, fx, period, duty, ph) => C.gusts.push({ x0: cx + dx0, x1: cx + dx1, y0: cy + dy0, y1: cy + dy1, fx, period, duty, ph })
  const rH = (o) => C.hazards.push({ ...o, x: cx + o.dx, y: cy + o.dy })

  // ============================================================ 2. 崩れ回廊（崩れる掛け点）
  // 主役: ひびの入った台座。掛けて 1.6 秒で落ちる。こいでいる暇はない。勢いを持ったまま掛けて振り抜く
  sec('crumble', 40, 92)
  R(6, 5)                                   // 13
  rl(4, 12, -8)                             // 受けの棚（初めての崩れは下に棚）
  R(7, 5, 'crumble')                        // 14: 初めて見せる
  R(7, 5); const p15 = P()                  // 15
  R(6, 5.5, 'crumble'); R(7, 5, 'crumble')  // 16, 17: 近道（崩れる点を2つ続けて）
  go(...p15)
  R(-7, 5); R(-6, 5); R(7, 4.5); R(6, 4)    // 18-21: 遠回り（ふつうの輪だけ）
  R(7, -2.5)                                // 22: 合流
  rl(6, 16, 6.5, 1.0, { mat: 'wood' })      // 張り出した床
  D(9, 3.5)                                 // 23: 罠（床の下。上へ抜けられない）
  R(-6, 5.5)                                // 24
  R(7, 5, 'crumble')                        // 25
  R(7, 3)                                   // 26: 床の上
  R(-6, 5, 'crumble')                       // 27: 試験
  rw(14, 18, -37, -1)                       // 右の控え壁
  F(-6, 4)                                  // 28 旗2

  // ============================================================ 3. 風の段（突風）
  // 主役: 周期で吹く横風。普通は届かない幅を、風が吹いた瞬間に離して越える。逆風の時は待つ
  sec('wind', 92, 140)
  R(6, 5); R(7, 4)                          // 29, 30
  rG(-2, 28, -8.5, 9.5, 22, 4, 0.45, 0)
  rw(6, 9, -16.5, -2.5)                     // 谷の手前の柱（下をくぐれない）
  R(17, 3.5)                                // 31: 風に乗って届く
  R(-6, 6); R(7, 5)                         // 32, 33
  rG(-26, 10, -5, 13, 20, 3.4, 0.5, 1.7)
  R(-11, 4)                                 // 34: 逆風の谷
  R(-7, 5, 'crumble')                       // 35: 逆風の中の崩れる点
  D(13, 5); D(7, 10.5)                      // 36, 37: 遠回り
  R(-5, 5)                                  // 38
  R(7, 5)                                   // 39
  rw(-16, -12, -22, 6)                      // 左の控え壁
  F(7, 4)                                   // 40 旗3

  // ============================================================ 4. 鐘楼（鐘と錆びた輪）
  // 主役: 鐘の輪。掛けると鐘が鳴り、壁から輪が出る・鎧戸が開く（7秒）。錆びた輪は一度離すと折れる
  sec('bell', 140, 196)
  R(6, 5)                                   // 41
  R(7, 4, 'bell', { g: 'b1' })              // 42
  R(7, 5.5, 'ring', { hidden: { g: 'b1' } })    // 43: 鐘で壁から出る輪
  R(-6, 6)                                  // 44
  R(-7, 4, 'rusty')                         // 45
  R(-7, 4)                                  // 46
  D(16, 2, 'rusty')                         // 47: 罠（錆びた輪の先に道がない）
  R(7, 4.5, 'bell', { g: 'b2' })            // 48
  R(-6, 4.5)                                // 49
  rB(-6, 4, 1.0, 8, { bell: { g: 'b2', dx: 0, dy: 9 }, mat: 'wood' })   // 縦の鎧戸（鐘で上へ開く）
  R(-8.5, 4)                                // 50: 鎧戸の向こう
  R(-6, 5)                                  // 51
  R(7, 4.5, 'rusty')                        // 52
  F(-7, 4)                                  // 53 旗4

  // ============================================================ 5. 風車の層（回る羽根と動く輪）
  // 主役: 塔に付いた古い風車。羽根に当たると手が離れる。回る輪に掛けると持ち上げてもらえる
  sec('mill', 196, 248)
  R(6, 5)                                   // 54
  rH({ k: 'blade', dx: 10, dy: 8, n: 4, len: 6, hw: 0.35, w: 0.7, ph: 0, reach: 9 })
  R(7, 0.5)                                 // 55
  R(10, 1)                                  // 56: 羽根の下をくぐる
  R(6, 9, 'ring', { move: { k: 'circle', r: 4.2, w: 0.7, ph: Math.PI / 2 } })   // 57: 回る輪
  R(6, 6)                                   // 58
  R(-8, 5)                                  // 59
  rH({ k: 'blade', dx: -5, dy: 8, n: 3, len: 5, hw: 0.35, w: -0.9, ph: 0.5, reach: 8.5 })
  R(-9, -1, 'ring', { move: { k: 'line', dx: 3.5, dy: 0, w: 1.1 } })   // 60: レールの輪
  R(-6, 6)                                  // 61
  R(-5, 4.5, 'crumble')                     // 62: 崩れる点は勢いの向きへ抜ける
  R(-6, 4)                                  // 63
  D(20, -2)                                 // 64: 遠回り
  R(7, 4.5)                                 // 65: 羽根の上
  F(7, 4)                                   // 66 旗5

  // ============================================================ 6. 鉄球の縦穴
  // 主役: 2本の柱の間の狭い縦穴。大きく振ると柱に当たる。振れる鉄球の合間を、小さく速く振って抜ける
  sec('shaft', 248, 306)
  rw(-10.5, -6.5, 5, 55)                    // 左の柱
  rw(7.5, 11.5, 5, 43)                      // 右の柱
  R(4.5, 6.5)                               // 67
  R(-8, 4.5); R(8, 4.5); R(-8, 4.5)         // 68-70
  R(8, 4.5)                                 // 71
  R(-8, 4.5)                                // 72
  R(8, 4.5)                                 // 73
  rH({ k: 'ball', dx: -4, dy: 18, L: 6, A: 0.45, w: 1.8, r: 1.0, ph: 1.4, reach: 10 })
  R(-8, 4.5); R(8, 4.5, 'rusty'); R(-8, 4.5); R(8, 4.5)   // 74-77
  R(6.5, 3.5)                               // 78: 穴の外
  F(6, 4)                                   // 79 旗6

  // ============================================================ 7. 砂の滝（下から上がる砂）
  // 主役: 区間に入ると砂が下から満ちてくる。止まって考える時間が短い
  sec('sand', 306, 356)
  C.floods.push({ x0: cx - 8, x1: cx + 32, y0: cy - 8, yMax: cy + 42, rate: 0.75, trigY: cy + 5, delay: 2.5 })
  R(6, 5)                                   // 80
  R(7, 4.5); R(-7, 4.5, 'crumble'); R(-6, 4); R(8, 4.5)  // 81-84
  rG(-16, 18, 1, 17, -20, 3.6, 0.45, 0.4)
  R(-10, 3.5)                               // 85: 風に乗って左へ
  R(-6, 5, 'crumble')                       // 86
  R(-6, 4)                                  // 87
  R(8, 4.5, 'ring', { move: { k: 'line', dx: 0, dy: 2.5, w: 1.2 } })  // 88: 上下する輪
  R(7, 4)                                   // 89
  F(7, 4)                                   // 90 旗7

  // ============================================================ 8. 頂の門（全部の組み合わせ）
  sec('crown', 356, 420)
  R(6, 5)                                   // 91
  R(7, 4, 'bell', { g: 'b3' })              // 92
  R(-7, 5, 'ring', { hidden: { g: 'b3' } }) // 93
  R(-7, 4.5, 'crumble')                     // 94
  R(-6, 4)                                  // 95
  R(8, 3, 'rusty')                          // 96
  R(7, 4.5)                                 // 97
  rG(-24, 6, 1, 17, -21, 3.8, 0.45, 2)
  R(-7, 5)                                  // 98
  R(-9, 3.5, 'crumble')                     // 99: 逆風の中を左へ
  R(-6, 4)                                  // 100
  rH({ k: 'blade', dx: 4.5, dy: 12.5, n: 4, len: 3.8, hw: 0.35, w: 0.8, ph: 0, reach: 8 })
  R(8, 4.5, 'rusty')                        // 101: 羽根の横
  rH({ k: 'ball', dx: -4, dy: 9.5, L: 5, A: 0.6, w: 1.5, r: 1.0, ph: 0.8, reach: 10 })
  R(-7, 4.5)                                // 102
  R(-7, 4.5, 'crumble')                     // 103
  rl(-20, -4, -1.5, 3, { rest: true })      // 頂上の門（崩れる点の勢いのまま左へ飛び込む）
  C.top = { x: cx - 12, y: cy - 1.3, w: 16 }

  C.spawn = { x: -8, y: 0.4 }
  C.bounds = { y0: -30 }
  return C
}
